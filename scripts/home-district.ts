/**
 * The home animation's heightmap (SPEC H4): the synthetic district run through our own pipeline.
 * Shared by scripts/build-home-heightmap.ts (writes the fixture) and test/home/model.test.ts
 * (checks that the committed fixture is what the pipeline produces today).
 */
import { generateHeightMap } from '../src/core/heightmap/index.ts';
import { importCityModel } from '../src/core/import/index.ts';
import { packHeightMap } from '../src/core/packing/pack.ts';
import { DISTRICT_CENTRE, syntheticDistrict } from '../src/core/samples/district.ts';
import { defaultParams, type Params } from '../src/core/types.ts';
import { APP_VERSION, HEIGHTMAP_ALGORITHM_VERSION, PACKING_ALGORITHM_VERSION } from '../src/core/version.ts';

export { HOME_FIXTURE_PATH } from './vite/home-model.ts';
export const HOME_DISTRICT_SEED = 7;

export function buildHomeHeightmap(date: string) {
  const files = syntheticDistrict(HOME_DISTRICT_SEED);
  const mesh = importCityModel(files);
  const area = { cx: DISTRICT_CENTRE[0], cy: DISTRICT_CENTRE[1], rotationDeg: 0 };
  const params: Params = {
    ...defaultParams(5, 3),
    scale: 6,
    heightMode: 'true-scale',
    heightRef: 'ground',
    sampling: 'centre-1',
    rotation: 'rotate',
    rounding: 'trunc',
    keepSmall: true,
  };
  const result = generateHeightMap(mesh, area, params);
  const hm = result.heightMap;
  const packing = packHeightMap(hm);
  if (result.vertical.maxValue > 24)
    throw new Error(`tallest column ${result.vertical.maxValue} > 24 bricks`);
  return {
    kind: 'legonizer-home-heightmap',
    formatVersion: 1,
    generated: {
      date,
      app: APP_VERSION,
      heightmapAlgorithm: HEIGHTMAP_ALGORITHM_VERSION,
      packingAlgorithm: PACKING_ALGORITHM_VERSION,
    },
    source: {
      dataset: 'synthetic-district',
      generator: `src/core/samples/district.ts syntheticDistrict(${HOME_DISTRICT_SEED})`,
      triangles: mesh.stats.triangles,
      features: mesh.stats.features,
      attribution: 'Generated by the Legonizer: an invented district, no real-world data',
      licence: 'Same licence as this site',
    },
    layout: {
      platesX: 5,
      platesY: 3,
      note: 'platesX west→east (table length), platesY north→south; north faces the mast (storyboard §1.1)',
    },
    area,
    params,
    inventory: { enabled: 'all', maxLength: 8 },
    grid: result.grid,
    heightMap: {
      cols: hm.cols,
      rows: hm.rows,
      order: 'data[j*cols + i], j south→north, i west→east',
      data: Array.from(hm.data),
    },
    summary: {
      maxBricks: result.vertical.maxValue,
      metresPerBrick: result.vertical.metresPerBrick,
      tallestCm: Math.round(result.vertical.maxValue * 9.6 * 10) / 100,
      studsWithBricks: hm.data.filter((v) => v > 0).length,
      totalBricks: packing.total,
      counts: packing.counts,
      baseplates: packing.baseplates.quantity,
      lowerBound: packing.lowerBound,
    },
  };
}
